import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 950 });
const errors = [];
p.on('pageerror', e => errors.push(String(e)));
await p.goto('https://dubai-lead-engine.vercel.app/', { waitUntil: 'networkidle0', timeout: 30000 });
await new Promise(r => setTimeout(r, 1000));
const t0 = await p.evaluate(() => { const r = document.getElementById('mascotInteractiveContainer').getBoundingClientRect(); return { l: r.left, pos: getComputedStyle(document.getElementById('mascotInteractiveContainer')).position }; });
await p.evaluate(() => document.querySelector('#problemAnchor').scrollIntoView({ block: 'center' }));
await new Promise(r => setTimeout(r, 2200));
const t1 = await p.evaluate(() => { const r = document.getElementById('mascotInteractiveContainer').getBoundingClientRect(); return { l: r.left }; });
await p.mouse.move(200, 250);
await new Promise(r => setTimeout(r, 800));
const t2 = await p.evaluate(() => { const r = document.getElementById('mascotInteractiveContainer').getBoundingClientRect(); return { l: r.left }; });
console.log('companion fixed:', t0.pos === 'fixed');
console.log('scroll glide works:', Math.abs(t1.l - t0.l) > 100, `(${Math.round(t0.l)} → ${Math.round(t1.l)})`);
console.log('cursor parallax works:', Math.abs(t2.l - t1.l) > 2, `(${Math.round(t1.l)} → ${Math.round(t2.l)})`);
console.log('JS errors:', errors.length, errors[0] || '');
await b.close();
